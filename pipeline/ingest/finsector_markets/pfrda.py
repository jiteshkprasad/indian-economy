"""PFRDA NPS/APY statistical data (tables A2, A5, M2, M4, M6): parsers.

Units: the files carry no caption; the Handbook of NPS Statistics 2024-25 (pinned; its 'References
for Data Tables' pages) states A2, A5 and M2 are 'Rs. in crore' and M6 'in crores'. M4 is not
captioned there either; it is read as Rs crore like its companion tables.

M4 ('Sector-wise NPS Contribution', given as on the last business day of the month) is read as a
cumulative stock of contributions: its levels are of the order of AUM and it rises month by month
(until the Feb-2026 break logged in the issues file). The unit derives annual contributions
FY 2015-16..2024-25 as the difference of end-March values (status 'derived'). The Handbook does not
say 'cumulative'; the reading is confirmed for the SG sector by Table M7 (SG contributions 'received
for the given month'), whose FY sums equal the M4 differences (FY 2023-24: 77,599.18 vs 77,599.20).

M7 ('State-wise Subscribers and contribution in SG Sector', monthly Dec-2014 onwards): only the
national 'Total' row is ingested (dataset <unit>_pfrda_sg): subscribers at month-end, and total,
employer and employee contributions received in the month (Rs crore), plus derived FY sums.

Vintage: these files are regenerated by PFRDA; the vintage is the server Last-Modified date of the
pinned bytes (from the pin's .meta.json).
"""

from __future__ import annotations

import datetime as dt
import email.utils
from typing import Any

from pipeline.core.unit import BuildContext, Dataset, RawFile
from pipeline.core.units import fy

from .common import Rows, cell_text, expect, frame, fy_label, load_xlsx, month_end, num

SRC = "pfrda_nps_statistics"
HANDBOOK = "HoNPSS_2024-25.pdf"
MONTHS = {m: i for i, m in enumerate(("JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"), 1)}
UNIT_NOTE = ("No unit caption in the file; 'Rs. in crore' per the Handbook of NPS Statistics 2024-25, 'References for "
             "Data Tables' (A2, A5, M2; M6 'in crores').")
SECTORS = {
    "APY": "apy", "ALL CITIZEN": "all_citizen", "CG": "central_govt", "CORPORATE": "corporate", "NPS LITE": "nps_lite",
    "NPS VATSALYA": "nps_vatsalya", "NPS VATSLYA": "nps_vatsalya", "SG": "state_govt", "MSF": "msf",
    "MSF TIER-I": "msf_tier1", "MSF TIER-II": "msf_tier2", "TTS": "tier2_tax_saver", "TIER-II": "tier2",
}
M6_CLASSES = {"AUM": "total", "CORPORATE BOND": "corporate_bonds", "EQUITY": "equity", "G-SEC": "gsec",
              "NCA": "cash_net_current_assets", "REIT & INVIT": "reit_invit", "SHORT TERM INVESTMENTS": "short_term"}


def _vintage(raw: RawFile) -> str:
    lm = (raw.meta.get("response_headers") or {}).get("last-modified")
    if not lm:
        raise ValueError(f"{raw.name}: no Last-Modified in the pin metadata; cannot date this vintage")
    return email.utils.parsedate_to_datetime(lm).astimezone(dt.UTC).date().isoformat()


def _month(label: Any) -> tuple[int, int]:
    s = str(label).strip().upper()
    mon, year = s.split("-")
    return int(year), MONTHS[mon]


def _sheet(ctx: BuildContext, name: str, title: str, first_header: str) -> tuple[RawFile, Any]:
    raw = ctx.raw(SRC, name)
    ws = load_xlsx(raw).worksheets[0]
    expect(ws, "A1", title)
    expect(ws, "A2", first_header)
    return raw, ws


def _columns(ws: Any, mapping: dict[str, str]) -> dict[int, tuple[str, str]]:
    cols = {}
    for c in range(2, ws.max_column + 1):
        h = cell_text(ws, 2, c)
        if not h:
            continue
        if h.upper() not in mapping:
            raise ValueError(f"PFRDA {ws['A1'].value!r}: unknown column {h!r}")
        cols[c] = (h, mapping[h.upper()])
    return cols


def _stock_table(ctx: BuildContext, out: list, name: str, title: str, table: str, first_header: str, mapping,
                 item: str, what: str, monthly: bool, label_fmt: str) -> str:
    raw, ws = _sheet(ctx, name, title, first_header)
    rows = Rows(ctx, SRC, _vintage(raw))
    cols = _columns(ws, mapping)
    data = []
    for r in range(3, ws.max_row + 1):
        a = ws.cell(r, 1).value
        if a is None or "-" not in str(a) or str(a).strip().upper()[:3] not in MONTHS:
            break
        y, m = _month(a)
        if not monthly and m != 3:
            raise ValueError(f"{table}: non-March row {a!r} in an annual table")
        data.append((r, month_end(y, m)))
    pid = rows.prov(
        raw, table_id=table,
        locator=f"sheet '{ws.title}', rows {data[0][0]}-{data[-1][0]} ({data[0][1][:7]}..{data[-1][1][:7]}), cols "
        f"B:{ws.cell(2, max(cols)).column_letter} ({', '.join(h for h, _ in cols.values())})",
        unit_as_published="Rs crore", release=f"PFRDA statistical data, {table} (file as regenerated on "
        f"{rows.vintage})", money=True, notes=f"{UNIT_NOTE} {what}",
    )
    for c, (h, code) in cols.items():
        for r, d in data:
            v = num(ws.cell(r, c).value)
            if v is None:
                continue
            rows.add(prov_id=pid, series_id=f"{table.split()[-1].lower()}.{item}.{code}.current", table_id=table,
                     item_code=item, item_label=label_fmt.format(h), value=v, unit="INR_crore", stock_flow="stock",
                     period=d, period_type="date", **({"instrument": code} if item == "aum_by_asset_class"
                                                     else {"institution": f"nps_{code}"}))
    out += rows.rows
    return pid


def build(ctx: BuildContext, unit: str) -> list[Dataset]:
    ctx.raw(SRC, HANDBOOK)  # pinned: the unit captions rest on it (hash-verified here)
    out: list[dict] = []
    _stock_table(ctx, out, "A2_sector-wise_asset_under_management.xlsx",
                 "Table A2: Sector-wise Asset Under Management under Tier-I", "Table A2",
                 "LAST BUSINESS DAY OF THE FY", SECTORS, "aum_tier1", "Tier-I AUM on the last business day of the FY "
                 "(dated 31 March here); APY Fund Scheme excluded per the Handbook.", False,
                 "Tier-I AUM, sector {}")
    _stock_table(ctx, out, "M2_sector_wise_asset_under_management.xlsx", "Table M2: Sector-wise Asset Under Management",
                 "Table M2", "LAST BUSINESS DAY OF THE MONTH", SECTORS, "aum", "AUM on the last business day of the "
                 "month (dated month-end here).", True, "AUM, sector {}")
    m4_pid = _stock_table(ctx, out, "M4_sector_wise_nps_contribution.xlsx", "Table M4: Sector-wise NPS Contribution",
                          "Table M4", "LAST BUSINESS DAY OF THE MONTH", SECTORS, "cumulative_contribution",
                          "Contribution 'as on the end of the month', read as cumulative contributions since inception "
                          "(inferred: levels close to AUM and rising monthly; break in Feb-2026). The published header "
                          "does not say 'cumulative'; the reading is confirmed for SG by Table M7 monthly flows (FY sums "
                          "2015-16..2024-25 equal the end-March differences within Rs 12 crore; 2023-24: 77,599.18 vs "
                          "77,599.20).", True,
                          "Contribution as on month-end, sector {}")
    _stock_table(ctx, out, "M6_asset_class_wise_classification.xlsx", "Table M6: Asset Class-wise classification of AUM",
                 "Table M6", "LAST BUSINESS DAY OF THE MONTH", M6_CLASSES, "aum_by_asset_class",
                 "Pension-fund portfolios on the last business day of the month, excluding deregistered pension "
                 "funds (table disclaimer).", True, "AUM by asset class: {}")

    # A5: Tier-II contributions settled during the FY (a flow)
    raw, ws = _sheet(ctx, "A5_sector-wise_contribution_in_tier.xlsx", "Table A5: Sector-wise Contribution to Tier II Account",
                     "YEAR")
    rows = Rows(ctx, SRC, _vintage(raw))
    cols = _columns(ws, SECTORS)
    data = []
    for r in range(3, ws.max_row + 1):
        a = ws.cell(r, 1).value
        if a is None:
            break
        data.append((r, fy_label(a)))
    pid = rows.prov(raw, table_id="Table A5",
                    locator=f"sheet '{ws.title}', rows {data[0][0]}-{data[-1][0]} ({data[0][1]}..{data[-1][1]}), cols "
                    f"B:{ws.cell(2, max(cols)).column_letter}", unit_as_published="Rs crore",
                    release=f"PFRDA statistical data, Table A5 (file as regenerated on {rows.vintage})", money=True,
                    notes=f"{UNIT_NOTE} Tier-II contribution settled during the FY; sector as of 31 March 2024 for "
                    "2023-24 and 31 March 2023 for earlier years (Handbook note).")
    for c, (h, code) in cols.items():
        for r, p in data:
            v = num(ws.cell(r, c).value)
            if v is None:
                continue
            rows.add(prov_id=pid, series_id=f"a5.tier2_contribution.{code}.current", table_id="Table A5",
                     item_code="tier2_contribution", item_label=f"Contribution to Tier II account, sector {h}",
                     value=v, unit="INR_crore", stock_flow="flow", period=p, period_type="fy", institution=f"nps_{code}")
    out += rows.rows

    # derived: annual contributions from M4 end-March levels, FY 2015-16..2024-25
    m4 = [r for r in out if r["series_id"].startswith("m4.")]
    by = {(r["series_id"], r["period"]): r for r in m4}
    vint = m4[0]["vintage"]
    dpid = ctx.prov(
        raw=None, source_id=SRC, table_id="Table M4 (derived)", locator="difference of the end-March rows of Table M4",
        unit_as_published="Rs crore", price_basis="current", vintage=vint,
        release=f"PFRDA statistical data, Table M4 (file as regenerated on {vint})", status="derived",
        method="Annual NPS contribution by sector in FY t = M4 cumulative contribution at end-March t+1 minus the value "
        "at end-March t (both as published). Valid only under the reading of M4 as cumulative contributions "
        "(confirmed for SG against Table M7 monthly flows; not independently checked for other sectors); FY "
        "2025-26 is not derived because of the Feb-2026 level break.",
        inputs=[m4_pid],
    )
    derived = []
    for sid in sorted({r["series_id"] for r in m4}):
        for y in range(2015, 2025):
            a, b = by.get((sid, f"{y}-03-31")), by.get((sid, f"{y + 1}-03-31"))
            if a is None or b is None:
                continue
            code = sid.split(".")[2]
            derived.append({**b, "series_id": f"m4d.annual_contribution.{code}.current", "table_id": "Table M4 (derived)",
                            "item_code": "annual_contribution",
                            "item_label": f"Annual contribution (derived from M4), sector {code}",
                            "stock_flow": "flow", "period": fy(y), "period_type": "fy",
                            "value": b["value"] - a["value"], "status": "derived", "prov_id": dpid})
    out += derived
    return [Dataset(f"{unit}_pfrda_nps", frame(out),
                    "PFRDA NPS/APY: sector-wise AUM (A2 annual, M2 monthly), cumulative contributions (M4) and derived "
                    "annual contributions, AUM by asset class (M6), Tier-II contributions (A5)"),
            Dataset(f"{unit}_pfrda_sg", frame(_m7(ctx)),
                    "PFRDA Table M7: NPS State Government sector, all-India total: subscribers at month-end and "
                    "contributions received in the month (total, employer, employee), with derived FY sums")]


M7_FIELDS = (  # (column offset in the 4-column month block, header, item code, label, unit, is_stock)
    (0, "No. of Subscribers", "subscribers", "No. of Subscribers (SG sector)", "count", True),
    (1, "Total Contribution Cr", "contribution_total", "Total Contribution (SG sector)", "INR_crore", False),
    (2, "Employer Contribution Cr", "contribution_employer", "Employer Contribution (SG sector)", "INR_crore", False),
    (3, "Employee Contribution Cr", "contribution_employee", "Employee Contribution (SG sector)", "INR_crore", False),
)


def _m7(ctx: BuildContext) -> list[dict]:
    """Table M7, national 'Total' row only: monthly flows (period 'YYYY-MM') and month-end subscribers."""
    raw = ctx.raw(SRC, "M7_state_wise_subscribers.xlsx")
    ws = load_xlsx(raw).worksheets[0]
    expect(ws, "A1", "Table M7: State-wise Subscribers and contribution in SG Sector")
    expect(ws, "A4", "STATE")
    tot = [r for r in range(5, ws.max_row + 1) if cell_text(ws, r, 1) == "Total"]
    if len(tot) != 1:
        raise ValueError(f"PFRDA M7: expected one 'Total' row, found {tot}")
    t = tot[0]
    blocks = []
    for c in range(3, ws.max_column + 1):
        h = ws.cell(2, c).value
        if h is None:
            continue
        if (c - 3) % 4:
            raise ValueError(f"PFRDA M7: month header {h!r} off the 4-column grid at column {c}")
        y, m = _month(h)  # 'Dec-14': two-digit year
        if not 0 <= y < 100:
            raise ValueError(f"PFRDA M7: month header {h!r} is not 'Mon-YY'")
        y += 2000
        for off, hdr, *_ in M7_FIELDS:
            if cell_text(ws, 3, c + off) != hdr:
                raise ValueError(f"PFRDA M7 {h}: column +{off} header {cell_text(ws, 3, c + off)!r}, expected {hdr!r}")
        blocks.append((c, y, m))
    months = [(y, m) for _, y, m in blocks]
    if months[0] != (2014, 12) or len(set(months)) != len(months) or months != sorted(months):
        raise ValueError(f"PFRDA M7: unexpected month blocks {months[:3]}..{months[-3:]}")
    rows = Rows(ctx, SRC, _vintage(raw))
    (c0, y0, m0), (c1, y1, m1) = blocks[0], blocks[-1]
    loc = (f"sheet '{ws.title}', row {t} ('Total'), one 4-column block per month ({y0}-{m0:02d} at "
           f"{ws.cell(2, c0).column_letter}..{y1}-{m1:02d} at {ws.cell(2, c1).column_letter}); state rows not read")
    rel = f"PFRDA statistical data, Table M7 (file as regenerated on {rows.vintage})"
    note = ("Handbook of NPS Statistics 2024-25, Table M7: subscribers 'as on end of the given month'; contributions "
            "'received for the given month', 'in crores'; total = employee + employer (holds within Rs 0.1 crore). "
            "File note 1: data include SABs of respective states.")
    pid_n = rows.prov(raw, table_id="Table M7", locator=f"{loc}; 'No. of Subscribers' columns",
                      unit_as_published="number", release=rel, money=False,
                      notes=note + " Subscribers dated month-end.")
    pid_c = rows.prov(raw, table_id="Table M7", locator=f"{loc}; the three contribution columns",
                      unit_as_published="Rs crore", release=rel, money=True, notes=note)
    for c, y, m in blocks:
        for off, _, code, label, unit, stock in M7_FIELDS:
            v = num(ws.cell(t, c + off).value)
            if v is None:
                continue
            rows.add(prov_id=pid_n if stock else pid_c,
                     series_id=f"m7.{code}.state_govt" + ("" if stock else ".current"), table_id="Table M7",
                     item_code=code, item_label=label, value=v, unit=unit, stock_flow="stock" if stock else "flow",
                     period=month_end(y, m) if stock else f"{y:04d}-{m:02d}", period_type="date" if stock else "month",
                     institution="nps_state_govt")
    dpid = ctx.prov(
        raw=None, source_id=SRC, table_id="Table M7 (derived)", locator="sum of the monthly 'Total' row of Table M7",
        unit_as_published="Rs crore", price_basis="current", vintage=rows.vintage, release=rel, status="derived",
        method="FY contribution of the SG sector = sum of the 12 monthly contributions April..March in the 'Total' "
        "row of Table M7 (as published); only FYs with all 12 months present.", inputs=[pid_c])
    flows = [r for r in rows.rows if r["stock_flow"] == "flow"]
    derived = []
    for code in ("contribution_total", "contribution_employer", "contribution_employee"):
        by_fy: dict[str, list[float]] = {}
        for r in flows:
            if r["item_code"] == code:
                y, m = int(r["period"][:4]), int(r["period"][5:])
                by_fy.setdefault(fy(y if m >= 4 else y - 1), []).append(r["value"])
        for f, vs in sorted(by_fy.items()):
            if len(vs) == 12:
                derived.append({**flows[0], "series_id": f"m7d.annual_{code}.state_govt.current",
                                "table_id": "Table M7 (derived)", "item_code": f"annual_{code}",
                                "item_label": f"Annual {code.replace('_', ' ')} (sum of the M7 months), SG sector",
                                "period": f, "period_type": "fy", "value": sum(vs), "status": "derived",
                                "prov_id": dpid})
    return rows.rows + derived

