#!/usr/bin/env node
// Generates src/data/contract.gen.ts from pipeline/export/schema/*.schema.json
// (PLAN §4.15: ownerless, deterministic; anyone may run it, nobody edits the output).
//   node scripts/gen-contract.mjs          write the file
//   node scripts/gen-contract.mjs --check  exit 1 if the file is stale
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = path.resolve(webDir, "..", "pipeline", "export", "schema");
const outFile = path.join(webDir, "src", "data", "contract.gen.ts");

export async function generate() {
  const files = fs.existsSync(schemaDir)
    ? fs.readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort()
    : [];
  const parts = [
    "/* eslint-disable */",
    "// GENERATED by web/scripts/gen-contract.mjs from pipeline/export/schema/*.schema.json.",
    "// Do not edit by hand: run `npm run gen:contract`. A unit test fails when this file is stale.",
    "",
  ];
  if (files.length === 0) {
    parts.push("// No schema files found in pipeline/export/schema/ yet.", "export {};", "");
    return { text: parts.join("\n"), files };
  }
  for (const f of files) {
    const schema = JSON.parse(fs.readFileSync(path.join(schemaDir, f), "utf8"));
    const name = f.replace(/\.schema\.json$/, "");
    const ts = await compile(schema, name, {
      bannerComment: "",
      additionalProperties: false,
      strictIndexSignatures: false,
      format: true,
      style: { printWidth: 120, singleQuote: false, semi: true, trailingComma: "all" },
      cwd: schemaDir,
      declareExternallyReferenced: true,
      unreachableDefinitions: false,
      ignoreMinAndMaxItems: true,
    });
    parts.push(`// ---- ${f}`, ts.trim(), "");
  }
  // Deduplicate identical declarations that several schemas pull in via $ref.
  const seen = new Set();
  const out = [];
  for (const block of parts.join("\n").split(/\n(?=export (?:type|interface) )/)) {
    const m = /^export (?:type|interface) (\w+)/.exec(block);
    if (m && seen.has(m[1])) continue;
    if (m) seen.add(m[1]);
    out.push(block);
  }
  return { text: out.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n", files };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { text, files } = await generate();
  if (files.length === 0) console.warn(`gen-contract: no schemas in ${schemaDir}; the generated file is empty`);
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : null;
  if (process.argv.includes("--check")) {
    if (current !== text) {
      console.error("gen-contract: src/data/contract.gen.ts is stale; run `npm run gen:contract`");
      process.exit(1);
    }
    console.log(`gen-contract: up to date (${files.length} schemas)`);
  } else if (current !== text) {
    fs.writeFileSync(outFile, text);
    console.log(`gen-contract: wrote src/data/contract.gen.ts from ${files.length} schemas`);
  } else {
    console.log(`gen-contract: unchanged (${files.length} schemas)`);
  }
}
